"""Phase 1 — SeedLM block-fit reproduction (Gates 1a/1b).

Fits weight blocks as  w ≈ U(seed) @ t  where U is a C×P matrix generated by a
16-bit Galois LFSR from `seed`, and t is P coefficients quantized to 4 bits
with a shared power-of-two exponent. Compares against an RTN int4 baseline.

Storage accounting per block of C weights (honest, per the project's storage-accounting ground rule):
    16 (seed) + 4 (shared exponent) + P*4 (coefficients)  bits
    C=8,  P=3  -> 4.0 bpw      C=12, P=4 -> 3.0 bpw

Scope cut (documented): we search N_SEEDS candidates per block, not
the full 2^16, so our floor is slightly above paper-SeedLM. All variants here
share that handicap, so comparisons between them remain fair.

Usage:
    python phase1_fit.py --synthetic              # Gate 1a
    python phase1_fit.py --model path/to/Qwen3-0.6B [--tensors N] [--outlier-pct P]
"""

import argparse
import time

import torch

# ----------------------------------------------------------------- LFSR / U
TAPS = 0xB400  # 16-bit Galois LFSR, maximal-length taps


def lfsr_states(seeds: torch.Tensor, n: int) -> torch.Tensor:
    """Vectorized Galois LFSR. seeds: [S] uint16-valued int64. Returns [S, n]
    successive 16-bit states. Bit-exact and platform-independent (Gate 1a)."""
    s = seeds.clone()
    out = torch.empty(len(seeds), n, dtype=torch.int64)
    for i in range(n):
        lsb = s & 1
        s = s >> 1
        s = torch.where(lsb.bool(), s ^ TAPS, s)
        s = torch.where(s == 0, torch.full_like(s, 1), s)  # never absorb at 0
        out[:, i] = s
    return out


def make_U(seeds: torch.Tensor, C: int, P: int, device) -> torch.Tensor:
    """[S, C, P] basis matrices with entries mapped to (-1, 1)."""
    states = lfsr_states(seeds, C * P).to(device)
    u = states.to(torch.float32) / 32767.5 - 1.0
    return u.view(-1, C, P)


# ------------------------------------------------------------- quantization
def quantize_coeffs(t: torch.Tensor):
    """4-bit coefficients with a shared power-of-two exponent per block.
    t: [..., P] -> (quantized ints in [-8,7], scale as 2^e)."""
    absmax = t.abs().amax(dim=-1, keepdim=True).clamp(min=1e-12)
    e = torch.ceil(torch.log2(absmax / 7.0))
    scale = torch.pow(2.0, e)
    q = torch.clamp(torch.round(t / scale), -8, 7)
    return q, scale


def rtn_int4(w: torch.Tensor, block: int = 32) -> torch.Tensor:
    """Baseline: symmetric absmax int4, block-32. Returns dequant."""
    flat = w.flatten()
    pad = (-flat.numel()) % block
    flat = torch.cat([flat, torch.zeros(pad, device=w.device)])
    blocks = flat.view(-1, block)
    scale = blocks.abs().amax(dim=1, keepdim=True).clamp(min=1e-12) / 7.0
    q = torch.clamp(torch.round(blocks / scale), -8, 7)
    return (q * scale).flatten()[: w.numel()].view(w.shape)


# ------------------------------------------------------------------ seed fit
def seedlm_fit(w: torch.Tensor, C: int, P: int, n_seeds: int,
               chunk: int = 8192, generator_seed: int = 3407):
    """Fit every C-block of w with the best of n_seeds candidate bases.
    Returns (dequantized tensor, mean bits/weight)."""
    device = w.device
    if n_seeds >= 65535:                      # full search, paper-style
        cand = torch.arange(1, 1 << 16, dtype=torch.int64)
    else:
        g = torch.Generator().manual_seed(generator_seed)
        cand = torch.randint(1, 1 << 16, (n_seeds,), generator=g, dtype=torch.int64)
    # keep the [S, b, C] recon buffer under ~1.5 GB regardless of seed count
    chunk = min(chunk, max(256, (1 << 31) // (len(cand) * (C + P) * 4)))

    U = make_U(cand, C, P, device)                     # [S, C, P]
    # Precompute pseudo-inverses once: [S, P, C]
    pinv = torch.linalg.pinv(U)

    flat = w.flatten().float()
    pad = (-flat.numel()) % C
    flat = torch.cat([flat, torch.zeros(pad, device=device)])
    blocks = flat.view(-1, C)                          # [B, C]

    out = torch.empty_like(blocks)
    for lo in range(0, blocks.shape[0], chunk):
        b = blocks[lo:lo + chunk]                      # [b, C]
        # t for every (seed, block): [S, b, P]
        t = torch.einsum("spc,bc->sbp", pinv, b)
        q, scale = quantize_coeffs(t)
        recon = torch.einsum("scp,sbp->sbc", U, q * scale)   # [S, b, C]
        err = (recon - b.unsqueeze(0)).pow(2).sum(-1)        # [S, b]
        best = err.argmin(dim=0)                             # [b]
        out[lo:lo + chunk] = recon[best, torch.arange(len(b), device=device)]

    bpw = (16 + 4 + P * 4) / C
    return out.flatten()[: w.numel()].view(w.shape), bpw


def with_outliers(w: torch.Tensor, pct: float, C: int, P: int, n_seeds: int):
    """Phase 2 preview: hold out top-pct% |w| in fp16+index, seed-fit the rest.
    Side-channel cost: 16 (value) + 32 (index) bits per outlier."""
    k = max(1, int(w.numel() * pct / 100))
    flat = w.flatten().float()
    idx = flat.abs().topk(k).indices
    kept = flat[idx].clone()
    masked = flat.clone()
    masked[idx] = 0.0
    deq, bpw = seedlm_fit(masked.view(w.shape), C, P, n_seeds)
    deq = deq.flatten()
    deq[idx] = kept
    bpw_total = bpw + k * (16 + 32) / w.numel()
    return deq.view(w.shape), bpw_total


# ---------------------------------------------------------------- reporting
def rel_err(w, deq):
    return ((w.float() - deq).norm() / w.float().norm()).item()


def run_synthetic(args):
    """Gate 1a: reproducibility + sanity on Gaussian data."""
    torch.manual_seed(0)
    dev = args.device
    # Reproducibility: identical states across two calls
    s = torch.tensor([1, 42, 65535], dtype=torch.int64)
    assert torch.equal(lfsr_states(s, 64), lfsr_states(s, 64)), "LFSR not deterministic"
    print("LFSR determinism        : OK")
    print(f"LFSR sample states(42)  : {lfsr_states(torch.tensor([42]), 5).tolist()[0]}")

    w = torch.randn(512, 512, device=dev) * 0.02
    deq, bpw = seedlm_fit(w, args.C, args.P, args.n_seeds)
    base = rtn_int4(w)
    print(f"gaussian 512x512 @ {bpw:.2f} bpw : seed {rel_err(w, deq):.4f}  "
          f"rtn4 {rel_err(w, base):.4f}")
    print("Gate 1a: PASS" if rel_err(w, deq) < 0.5 else "Gate 1a: INVESTIGATE")


def run_model(args):
    """Gate 1b: real tensors, seed fit vs RTN."""
    from safetensors import safe_open
    import glob, os
    paths = sorted(glob.glob(os.path.join(args.model, "*.safetensors")))
    assert paths, f"no safetensors under {args.model}"

    names = []
    with safe_open(paths[0], framework="pt") as f:
        for n in f.keys():
            if n.endswith(".weight") and any(
                    k in n for k in ("q_proj", "o_proj", "gate_proj", "down_proj")):
                names.append(n)
    # spread picks across depth
    names = sorted(names)[:: max(1, len(names) // args.tensors)][: args.tensors]

    wins = 0
    print(f"{'tensor':<52}{'bpw':>6}{'seed':>9}{'rtn4':>9}{'winner':>8}")
    for n in names:
        with safe_open(paths[0], framework="pt") as f:
            w = f.get_tensor(n).to(args.device)
        t0 = time.time()
        if args.outlier_pct > 0:
            deq, bpw = with_outliers(w, args.outlier_pct, args.C, args.P, args.n_seeds)
        else:
            deq, bpw = seedlm_fit(w, args.C, args.P, args.n_seeds)
        e_seed, e_rtn = rel_err(w, deq), rel_err(w, rtn_int4(w))
        win = e_seed < e_rtn
        wins += win
        print(f"{n:<52}{bpw:>6.2f}{e_seed:>9.4f}{e_rtn:>9.4f}"
              f"{'seed' if win else 'rtn':>8}  ({time.time()-t0:.1f}s)")
    frac = wins / len(names)
    print(f"\nseed wins {wins}/{len(names)} tensors ({frac:.0%})")
    print("Gate 1b: PASS" if frac >= 0.8 else "Gate 1b: FAIL (or raise --n-seeds)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", help="path to a safetensors model dir")
    ap.add_argument("--synthetic", action="store_true")
    ap.add_argument("--tensors", type=int, default=8)
    ap.add_argument("--C", type=int, default=8)
    ap.add_argument("--P", type=int, default=3)
    ap.add_argument("--n-seeds", type=int, default=2048)
    ap.add_argument("--outlier-pct", type=float, default=0.0,
                    help="Phase 2 preview: %% of weights held out exactly")
    ap.add_argument("--device",
                    default="cuda" if torch.cuda.is_available() else "cpu")
    args = ap.parse_args()
    if args.synthetic:
        run_synthetic(args)
    else:
        assert args.model, "--model required (or use --synthetic)"
        run_model(args)
